package com.zifang.z.wf.core.model;

/**
 * job 的种类。
 *
 * <p>三种边界事件共用 {@link WfJob} 这一个载体，但触发方式完全不同：
 * <ul>
 *   <li>{@link #TIMER} —— 到点即响，由扫描器捞</li>
 *   <li>{@link #MESSAGE} —— 特定流程实例的特定消息到达时响</li>
 *   <li>{@link #SIGNAL} —— 广播信号时响，可能一次命中多个实例</li>
 * </ul>
 *
 * <p>为什么不用"duedate 为 null 就不是定时器"来区分：那是个隐式约定，
 * 任何人写 {@code saveJob} 时都可能漏掉，于是消息订阅被扫描器当成到期 job 消费掉 ——
 * 表现是"还没发消息，流程自己往前走了"，极难定位。所以这里给一个显式字段。
 *
 * @author zifang
 */
public enum WfJobType {

    /** 定时器边界：按 duedate 到期。 */
    TIMER("定时器"),

    /** 消息边界：订阅某个消息名，消息到达时触发。 */
    MESSAGE("消息"),

    /** 信号边界：订阅某个信号名，广播时触发。 */
    SIGNAL("信号"),

    /**
     * 外部任务：停在某个 topic 上等外部 worker 来取。
     *
     * <p>与前三种的根本区别：它<b>不由时间或消息触发</b>，而是等着被人来领。
     * 没有它，流程要调外部系统就只能同步阻塞在引擎线程里 ——
     * 外部系统慢会把审批线程池拖住，外部系统挂了整条流程一起卡死。
     */
    EXTERNAL("外部任务"),

    /**
     * 升级边界订阅：宿主节点上挂一条「被升级事件点名就升级」的订阅。
     *
     * <p><b>单独一个类型而不是复用 {@link #SIGNAL}</b>：两者投递方式一样（广播），
     * 但<b>可被投的人不同</b> —— 信号是"谁订阅了信号名就叫醒谁"，
     * 升级是"谁在等这个 escalationCode 就升级谁"。
     *
     * <p><b>升级实际做了什么</b>（不要按字面理解成"引擎替谁换人"）：
     * 它调用的是与消息 / 信号边界同一条 {@code fireEventBoundary} 路径 ——
     * 中断型把宿主那条 token 搬到边界事件上、<b>宿主上的待办作废</b>；
     * 非中断型（{@code cancelActivity="false"}）宿主照常办、另起一条升级分支。
     * 边界自己的出线节点再照常建待办 —— **"换给谁办"取决于那条出线上写了谁**，
     * 引擎不替作者决定。写成"引擎按 escalationConfig 换人"是假的：那一层本实现没有。
     *
     * <p>那为什么要独立一个类型：升级在审批里的意图通常是"这次不能就这么算了"，
     * 而信号只是"通知一声"。共用一个类型的话，投递方就得靠名字猜该不该打断，
     * 猜错的后果是<b>把一条升级当成普通信号处理</b> —— 分支醒了、待办还挂着、人没变，
     * 而作者以为已经升级过了。
     *
     * <p><b>本类型只表示"按名字触发"，duedate 恒为 null</b>：
     * 到期自动升级（Camunda 的 escalationTimer）明确不支持，
     * 配了 timerEventDefinition 会在部署期报错（见 {@code WfXmlParser#parseEscalationDefinition}）。
     * 原因写在 {@link #EVENT_TIMER} 里：到期触发与按名字触发混进同一个 job，
     * 触发方就必须去猜"这条是不是已经到期了"。
     */
    ESCALATION("升级边界"),

    /**
     * 异步前置：token 到达节点后、执行它之前挂起。
     *
     * <p>job 执行时<b>进入</b>该节点，把它的行为真正跑一遍（建任务 / 跑 delegate）。
     * 与 {@link #ASYNC_AFTER} 分成两个类型而不是共用一个，是因为两者的续跑动作
     * 方向相反：共用一个的话，执行器就必须去查"这到底是前置还是后置"，
     * 而那个信息本来就该由 job 自己携带。
     */
    ASYNC_BEFORE("异步前置"),

    /**
     * 异步后置：节点已执行完、离开之前挂起。
     *
     * <p>job 执行时<b>离开</b>该节点、沿出线前进 —— 节点本身不会再跑一遍。
     */
    ASYNC_AFTER("异步后置"),

    /**
     * 事件网关的<b>消息分支</b>：token 停在这个网关的某个中间捕获事件上等这条消息。
     *
     * <p><b>必须与 {@link #MESSAGE} 分开</b>，因为两者的触发后果完全不同：
     * {@link #MESSAGE} 是<b>打断</b>（宿主上的待办作废、token 被拉到边界事件上走补偿分支），
     * 而这里是<b>竞速</b>（本分支前进，其余分支连同各自的等待一并作废）。
     * 共用一个类型的话，触发路径必须去查"这到底是打断还是竞速"，
     * 而查错的后果不是报错，是流程静默走错分支。
     *
     * <p>事件名存在 {@code exceptionMessage} 里，与 {@link #MESSAGE} 同一约定。
     */
    EVENT_MESSAGE("事件网关-消息"),

    /**
     * 事件网关的<b>信号分支</b>。与 {@link #EVENT_MESSAGE} 同理，信号可以命中多条分支，
     * 每条命中都要各自走一次竞速（而不是只走一条）。
     */
    EVENT_SIGNAL("事件网关-信号"),

    /**
     * 事件网关的<b>定时器分支</b>。与 {@link #EVENT_MESSAGE} 同理是<b>竞速</b>：
     * 到点即算这一条赢了，其余分支连同各自的等待一并作废。
     *
     * <p><b>刻意不与 {@link #TIMER} 共用类型</b>，尽管两者都是"时间到了触发"：
     * {@link #TIMER} 装的是<b>边界打断</b>（拉 token 到边界事件走补偿分支），
     * 这里装的是<b>竞速</b>（自己前进、其余兄弟作废）。
     * 共用类型的后果本轮真的踩到了 —— 落选分支的清理是"按 job 类型白名单"做的，
     * 白名单里没有新的定时器形态，于是<b>输掉的定时器 job 不会被删</b>，
     * 到点后它会去触发一条已经不在那一格上的 token。
     * 症状是流程被静默地多推一次，或者干脆什么都不发生且不报错。
     * 所以这里恢复类型分离：宁可多一个枚举值，也不要让触发路径去猜。
     */
    EVENT_TIMER("事件网关-定时器");

    private final String label;

    WfJobType(String label) {
        this.label = label;
    }

    public String getLabel() {
        return label;
    }

    /**
     * 写进活动历史 outcome 的前缀（如 {@code timer:}）。
     *
     * <p>带前缀是为了让"这次节点访问是被什么打断的"从轨迹上就能读出来 ——
     * 事后追责时不必再去翻评论。定时器这一支的 {@code timer:} 是既有契约。
     */
    public String outcomePrefix() {
        return name().toLowerCase() + ":";
    }
}
